/** Emits src/generated/names.ts from icons.config.ts and fails if any Lucide export is missing. */
import { mkdir, writeFile } from 'node:fs/promises';
import * as lucide from 'lucide-react';
import { ICONS } from '../icons.config.ts';

const missing = Object.entries(ICONS).filter(([, exp]) => !(exp in lucide));
if (missing.length) {
  console.error('Unknown Lucide exports:', missing.map(([k, v]) => `${k} → ${v}`).join(', '));
  process.exit(1);
}
const entries = Object.entries(ICONS);
const out = `// Generated by scripts/generate.ts from icons.config.ts. Do not edit.
import {
${entries.map(([, exp]) => `  ${exp},`).join('\n')}
} from 'lucide-react';

export const icons = {
${entries.map(([k, exp]) => `  '${k}': ${exp},`).join('\n')}
} as const;

export type IconName = keyof typeof icons;
export const iconNames = Object.keys(icons) as IconName[];
`;
await mkdir('src/generated', { recursive: true });
await writeFile('src/generated/names.ts', out);
console.log(`@macaw-ds/icons: ${entries.length} icons`);
