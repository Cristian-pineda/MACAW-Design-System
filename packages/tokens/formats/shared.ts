import type { TransformedToken } from 'style-dictionary/types';

export const PREFIX = 'macaw';

/** Mirrors Style Dictionary's name/kebab transform so references can be rewritten to var(). */
export function kebabPath(path: string[]): string {
  return [PREFIX, ...path]
    .join(' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[\s._]+/g, '-')
    .toLowerCase();
}

export function tierOf(token: TransformedToken): 'primitive' | 'semantic' | 'component' {
  const fp = token.filePath ?? '';
  if (fp.includes('/primitive/')) return 'primitive';
  if (fp.includes('/component/')) return 'component';
  return 'semantic';
}

const REF = /\{([^}]+)\}/g;

export function hasReference(value: unknown): value is string {
  return typeof value === 'string' && REF.test(value) && ((REF.lastIndex = 0), true);
}

/** `{color.action.primary}` → `var(--macaw-color-action-primary)` */
export function referencesToVars(value: string): string {
  return value.replace(REF, (_m, p: string) => `var(--${kebabPath(p.split('.'))})`);
}

export function header(): string {
  return `/* Generated by @macaw-ds/tokens. Do not edit; edit src/*.json and run pnpm build. */\n`;
}
